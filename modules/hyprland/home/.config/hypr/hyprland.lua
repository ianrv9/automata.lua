-- personal.lua goes last so it can override anything
do
    local path = HOME .. "/.config/hypr/personal.lua"
    local f = io.open(path, "r")
    if f then
        f:close()
        local ok, err = pcall(dofile, path)
        if not ok then hl.exec_cmd("notify-send -u critical '@@t:personal_error@@' " .. string.format("%q", tostring(err))) end
    end
end
