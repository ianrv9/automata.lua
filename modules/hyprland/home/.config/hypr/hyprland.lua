hl.config({ autogenerated = false })

local HOME = os.getenv("HOME")

-- Reads KEY="value" lines. Missing file or key = the default you pass to set()
local settings = {}
do
    local f = io.open(HOME .. "/.config/automata/settings.conf", "r")
    if f then
        for line in f:lines() do
            local k, v = line:match('^([%u_]+)="(.-)"')
            if k then settings[k] = v:gsub("%$HOME", HOME) end
        end
        f:close()
    end
end
local function set(key, default) return settings[key] or default end
local function num(key, default) return tonumber(settings[key]) or default end

