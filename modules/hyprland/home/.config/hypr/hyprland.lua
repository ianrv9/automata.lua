-- Animations. "relaxed" just slows everything down
local slow = set("ANIMATIONS", "fast") == "relaxed" and 1.8 or 1
local function speed(s) return s * slow end

hl.curve("hud",     { type = "bezier", points = { {0.05, 0.9}, {0.1, 1.0} } })
hl.curve("hudOut",  { type = "bezier", points = { {0.3, 0.0},  {0.2, 1.0} } })   -- leaves fast from frame one, or closing windows look frozen
hl.curve("linear",  { type = "bezier", points = { {0, 0},      {1, 1} } })
hl.curve("soft",    { type = "spring", mass = 1, stiffness = 260, dampening = 26 })

hl.animation({ leaf = "global",           enabled = true, speed = speed(8),   bezier = "default" })
hl.animation({ leaf = "border",           enabled = true, speed = speed(6),   bezier = "hud" })
hl.animation({ leaf = "windows",          enabled = true, speed = speed(4),   spring = "soft" })
hl.animation({ leaf = "windowsIn",        enabled = true, speed = speed(3.5), bezier = "hud",    style = "popin 90%" })
hl.animation({ leaf = "windowsOut",       enabled = true, speed = speed(2),   bezier = "hudOut", style = "popin 90%" })
hl.animation({ leaf = "fade",             enabled = true, speed = speed(3),   bezier = "hud" })
hl.animation({ leaf = "layersIn",         enabled = true, speed = speed(3),   bezier = "hud",    style = "slide" })
hl.animation({ leaf = "layersOut",        enabled = true, speed = speed(2),   bezier = "hudOut", style = "fade" })
hl.animation({ leaf = "workspaces",       enabled = true, speed = speed(3.5), bezier = "hud",    style = "slidefade 12%" })
hl.animation({ leaf = "specialWorkspace", enabled = true, speed = speed(3.5), bezier = "hud",    style = "slidefadevert 20%" })
hl.animation({ leaf = "zoomFactor",       enabled = true, speed = speed(7),   bezier = "hud" })

